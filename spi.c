#define LATCH (1<<1)
#define OE (1<<2)

#define pulseLength 2000
#define tempdelay 500

void send_spi(uint8_t data) {
	GPIOC->OUTDR |= OE;

	// wait for TXE
	while(!(SPI1->STATR & SPI_STATR_TXE));
	// Send byte
	SPI1->DATAR = data;

	while(SPI1->STATR & SPI_STATR_BSY);

	GPIOC->OUTDR &= ~OE;
	GPIOC->OUTDR |= LATCH;
	Delay_Us(pulseLength);
	GPIOC->OUTDR |= OE;
	GPIOC->OUTDR &= ~LATCH;
}

